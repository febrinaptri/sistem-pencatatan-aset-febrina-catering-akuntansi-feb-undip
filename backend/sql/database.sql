create or replace function public.posting_jurnal_penyusutan(
  p_periode date,
  p_akun_beban_id bigint,
  p_akun_akumulasi_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_akun_beban public.akun%rowtype;
  v_akun_akumulasi public.akun%rowtype;
  v_aset record;
  v_id_jurnal bigint;
  v_nomor_jurnal text;
  v_akhir_periode date;
  v_akhir_sebelumnya date;
  v_umur_bulan integer;
  v_bulan_berjalan integer;
  v_bulan_sebelumnya integer;
  v_dasar_penyusutan numeric;
  v_penyusutan_bulanan numeric;
  v_akumulasi_sekarang numeric;
  v_akumulasi_sebelumnya numeric;
  v_beban_periode numeric;
  v_total numeric := 0;
begin
  if p_periode is null or extract(day from p_periode) <> 1 then
    raise exception 'Periode harus berupa tanggal pertama pada bulan yang dipilih.' using errcode = '22007';
  end if;

  v_akhir_periode := (p_periode + interval '1 month - 1 day')::date;
  v_akhir_sebelumnya := (p_periode - 1)::date;

  select * into v_akun_beban from public.akun where id_akun = p_akun_beban_id;
  if not found or not v_akun_beban.is_aktif
    or v_akun_beban.jenis_akun <> 'Beban' or v_akun_beban.saldo_normal <> 'Debit'
    or v_akun_beban.nama_akun !~* 'penyusutan' then
    raise exception 'Pilih akun Beban Penyusutan aktif dengan saldo normal Debit.' using errcode = '23514';
  end if;

  select * into v_akun_akumulasi from public.akun where id_akun = p_akun_akumulasi_id;
  if not found or not v_akun_akumulasi.is_aktif
    or v_akun_akumulasi.jenis_akun <> 'Aset' or v_akun_akumulasi.saldo_normal <> 'Kredit'
    or v_akun_akumulasi.nama_akun !~* 'akumulasi.*penyusutan|penyusutan.*akumulasi' then
    raise exception 'Pilih akun Akumulasi Penyusutan aktif dengan saldo normal Kredit.' using errcode = '23514';
  end if;

  if p_akun_beban_id = p_akun_akumulasi_id then
    raise exception 'Akun beban dan akumulasi harus berbeda.' using errcode = '23514';
  end if;

  v_nomor_jurnal := 'JPS-' || to_char(p_periode, 'YYYYMM');
  insert into public.jurnal (nomor_jurnal, tanggal_jurnal, jenis_jurnal, periode, deskripsi)
  values (
    v_nomor_jurnal,
    v_akhir_periode,
    'Penyusutan',
    p_periode,
    'Penyusutan aset tetap periode ' || to_char(p_periode, 'YYYY-MM')
  )
  returning id_jurnal into v_id_jurnal;

  for v_aset in
    select id_aset, nama_aset, tanggal_pembelian, harga_perolehan, umur_manfaat_tahun, nilai_residu
    from public.aset
    where tanggal_pembelian <= v_akhir_periode
      and umur_manfaat_tahun between 1 and 100
    order by id_aset
    for update
  loop
    v_umur_bulan := v_aset.umur_manfaat_tahun * 12;
    v_dasar_penyusutan := greatest(0, v_aset.harga_perolehan - v_aset.nilai_residu);
    v_penyusutan_bulanan := v_dasar_penyusutan / v_umur_bulan;

    v_bulan_berjalan := (extract(year from v_akhir_periode)::integer - extract(year from v_aset.tanggal_pembelian)::integer) * 12
      + extract(month from v_akhir_periode)::integer - extract(month from v_aset.tanggal_pembelian)::integer;
    if extract(day from v_akhir_periode) < extract(day from v_aset.tanggal_pembelian) then
      v_bulan_berjalan := v_bulan_berjalan - 1;
    end if;
    v_bulan_berjalan := greatest(0, least(v_bulan_berjalan, v_umur_bulan));

    v_bulan_sebelumnya := (extract(year from v_akhir_sebelumnya)::integer - extract(year from v_aset.tanggal_pembelian)::integer) * 12
      + extract(month from v_akhir_sebelumnya)::integer - extract(month from v_aset.tanggal_pembelian)::integer;
    if extract(day from v_akhir_sebelumnya) < extract(day from v_aset.tanggal_pembelian) then
      v_bulan_sebelumnya := v_bulan_sebelumnya - 1;
    end if;
    v_bulan_sebelumnya := greatest(0, least(v_bulan_sebelumnya, v_umur_bulan));

    v_akumulasi_sekarang := least(v_dasar_penyusutan, v_penyusutan_bulanan * v_bulan_berjalan);
    v_akumulasi_sebelumnya := least(v_dasar_penyusutan, v_penyusutan_bulanan * v_bulan_sebelumnya);
    v_beban_periode := greatest(0, round(v_akumulasi_sekarang) - round(v_akumulasi_sebelumnya));

    if v_beban_periode > 0 then
      insert into public.jurnal_detail (id_jurnal, akun_id, posisi, jumlah, keterangan)
      values
        (v_id_jurnal, v_akun_beban.id_akun, 'Debit', v_beban_periode, 'Penyusutan ' || v_aset.nama_aset),
        (v_id_jurnal, v_akun_akumulasi.id_akun, 'Kredit', v_beban_periode, 'Penyusutan ' || v_aset.nama_aset);
      v_total := v_total + v_beban_periode;
    end if;
  end loop;

  if v_total <= 0 then
    raise exception 'Tidak ada beban penyusutan untuk periode ini.' using errcode = '22023';
  end if;

  return v_id_jurnal;
end;
$$;

revoke all on function public.posting_jurnal_penyusutan(date, bigint, bigint) from public;
grant execute on function public.posting_jurnal_penyusutan(date, bigint, bigint) to anon;

create or replace function public.catat_saldo_awal(
  p_tanggal date,
  p_baris jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_baris record;
  v_akun public.akun%rowtype;
  v_id_jurnal bigint;
  v_nomor_jurnal text;
  v_total_debit numeric := 0;
  v_total_kredit numeric := 0;
  v_jumlah_baris integer := 0;
begin
  if p_tanggal is null then
    raise exception 'Tanggal saldo awal wajib diisi.' using errcode = '22007';
  end if;

  if jsonb_typeof(p_baris) <> 'array' or jsonb_array_length(p_baris) < 2 then
    raise exception 'Isi saldo awal minimal dua akun.' using errcode = '22023';
  end if;

  if exists (
    select 1
    from public.jurnal
    where jenis_jurnal = 'Saldo Awal'
  ) then
    raise exception 'Saldo awal sudah pernah dicatat dan hanya dapat dibuat satu kali.' using errcode = '23505';
  end if;

  if exists (
    select 1
    from public.jurnal
    where jenis_jurnal <> 'Saldo Awal' and tanggal_jurnal <= p_tanggal
  ) then
    raise exception 'Tanggal saldo awal harus lebih awal dari jurnal transaksi yang sudah tercatat.' using errcode = '23514';
  end if;

  if exists (
    select akun_id
    from jsonb_to_recordset(p_baris) as baris(akun_id bigint, posisi text, jumlah numeric)
    group by akun_id
    having count(*) > 1
  ) then
    raise exception 'Setiap akun hanya boleh dicantumkan satu kali.' using errcode = '23514';
  end if;

  v_nomor_jurnal := 'SA-' || to_char(p_tanggal, 'YYYYMMDD');
  insert into public.jurnal (nomor_jurnal, tanggal_jurnal, jenis_jurnal, periode, deskripsi)
  values (
    v_nomor_jurnal,
    p_tanggal,
    'Saldo Awal',
    date_trunc('month', p_tanggal)::date,
    'Saldo awal akun per ' || to_char(p_tanggal, 'DD-MM-YYYY')
  )
  returning id_jurnal into v_id_jurnal;

  for v_baris in
    select * from jsonb_to_recordset(p_baris) as baris(akun_id bigint, posisi text, jumlah numeric)
  loop
    if v_baris.jumlah is null or v_baris.jumlah <= 0
      or v_baris.posisi not in ('Debit', 'Kredit') then
      raise exception 'Nominal harus positif dan posisi harus Debit atau Kredit.' using errcode = '23514';
    end if;

    select * into v_akun from public.akun where id_akun = v_baris.akun_id;
    if not found or not v_akun.is_aktif or v_akun.saldo_normal <> v_baris.posisi then
      raise exception 'Akun harus aktif dan posisi harus mengikuti saldo normal akun.' using errcode = '23514';
    end if;

    insert into public.jurnal_detail (id_jurnal, akun_id, posisi, jumlah, keterangan)
    values (v_id_jurnal, v_akun.id_akun, v_baris.posisi, v_baris.jumlah, 'Saldo awal');

    if v_baris.posisi = 'Debit' then
      v_total_debit := v_total_debit + v_baris.jumlah;
    else
      v_total_kredit := v_total_kredit + v_baris.jumlah;
    end if;
    v_jumlah_baris := v_jumlah_baris + 1;
  end loop;

  if v_jumlah_baris < 2 or round(v_total_debit, 2) <> round(v_total_kredit, 2) then
    raise exception 'Total saldo awal debit dan kredit harus sama.' using errcode = '23514';
  end if;

  return v_id_jurnal;
end;
$$;

