create or replace function public.catat_jurnal_perolehan(
  p_id_aset bigint,
  p_akun_aset_id bigint,
  p_akun_sumber_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_aset public.aset%rowtype;
  v_akun_aset public.akun%rowtype;
  v_akun_sumber public.akun%rowtype;
  v_id_jurnal bigint;
  v_nomor_jurnal text;
begin
  select * into v_aset
  from public.aset
  where id_aset = p_id_aset
  for update;

  if not found then
    raise exception 'Aset tidak ditemukan.' using errcode = 'P0002';
  end if;

  if exists (
    select 1 from public.jurnal
    where id_aset = p_id_aset and jenis_jurnal = 'Perolehan Aset'
  ) then
    raise exception 'Jurnal perolehan untuk aset ini sudah tercatat.' using errcode = '23505';
  end if;

  select * into v_akun_aset from public.akun where id_akun = p_akun_aset_id;
  if not found or not v_akun_aset.is_aktif
    or v_akun_aset.jenis_akun <> 'Aset' or v_akun_aset.saldo_normal <> 'Debit'
    or v_akun_aset.nama_akun ~* '(kas|bank)' then
    raise exception 'Akun debit harus berupa akun Aset aktif dengan saldo normal Debit.' using errcode = '23514';
  end if;

  select * into v_akun_sumber from public.akun where id_akun = p_akun_sumber_id;
  if not found or not v_akun_sumber.is_aktif
    or not (
      (v_akun_sumber.jenis_akun = 'Aset' and v_akun_sumber.saldo_normal = 'Debit'
        and v_akun_sumber.nama_akun ~* '(kas|bank)')
      or (v_akun_sumber.jenis_akun = 'Liabilitas' and v_akun_sumber.saldo_normal = 'Kredit')
    ) then
    raise exception 'Akun sumber harus berupa akun Kas/Bank atau Liabilitas aktif.' using errcode = '23514';
  end if;

  if p_akun_aset_id = p_akun_sumber_id then
    raise exception 'Akun aset dan akun sumber harus berbeda.' using errcode = '23514';
  end if;

  v_nomor_jurnal := 'JPA-' || to_char(v_aset.tanggal_pembelian, 'YYYYMMDD')
    || '-' || lpad(v_aset.id_aset::text, 6, '0');

  insert into public.jurnal (nomor_jurnal, tanggal_jurnal, jenis_jurnal, id_aset, deskripsi)
  values (
    v_nomor_jurnal,
    v_aset.tanggal_pembelian,
    'Perolehan Aset',
    v_aset.id_aset,
    'Perolehan aset ' || v_aset.nama_aset
  )
  returning id_jurnal into v_id_jurnal;

  insert into public.jurnal_detail (id_jurnal, akun_id, posisi, jumlah, keterangan)
  values
    (v_id_jurnal, v_akun_aset.id_akun, 'Debit', v_aset.harga_perolehan, v_aset.nama_aset),
    (v_id_jurnal, v_akun_sumber.id_akun, 'Kredit', v_aset.harga_perolehan, v_aset.nama_aset);

  return v_id_jurnal;
end;
$$;

revoke all on function public.catat_jurnal_perolehan(bigint, bigint, bigint) from public;
